-- Políticas: Lectura pública para datos históricos
CREATE POLICY "Lectura pública de jugadores" ON players FOR SELECT USING (TRUE);
CREATE POLICY "Lectura pública de partidos" ON matches FOR SELECT USING (TRUE);
CREATE POLICY "Lectura pública de stats" ON player_match_stats FOR SELECT USING (TRUE);
CREATE POLICY "Lectura pública de staff" ON staff_history FOR SELECT USING (TRUE);
CREATE POLICY "Lectura pública de leyendas" ON legends FOR SELECT USING (TRUE);
CREATE POLICY "Lectura pública de sponsors" ON sponsors FOR SELECT USING (TRUE);
CREATE POLICY "Lectura pública de preguntas" ON game_questions FOR SELECT USING (TRUE);

-- Perfiles y sesiones solo para usuario autenticado
CREATE POLICY "Perfil propio" ON user_profiles FOR ALL USING (auth.uid() = id);
CREATE POLICY "Sesiones propias" ON game_sessions FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "Chat propio" ON chat_history FOR ALL USING (auth.uid() = user_id);
